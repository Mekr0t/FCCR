r"""Build results/truncation_ablation.md (tables only) from the predictions of the S2-4 runs.

Usage:
    .venv\Scripts\python.exe scripts\truncation_ablation.py

Reads results/<run>/predictions.json (local, gitignored) of the reference dense runs and the
dense_*_dev_origeng_* / *_both_chunk* runs, scores them through src/evaluate.evaluate and splits
the posts into affected (`both` text > 512 tokens, from cache/<model>/train_dev_sets/both_posts/
ntok.npy: tokens of "query: " + text, <s> and </s> included) and unaffected. Overall = official
headline (mono: macro over languages, cross: micro); subsets = micro over posts.
Only the block between the TABLES markers is rewritten; text around it (interpretation) is kept.
"""

import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)

import numpy as np  # noqa: E402

from src.data import eval_units, load_reference  # noqa: E402
from src.evaluate import evaluate, official_score  # noqa: E402
from src.retrieval.combine import subset_metrics  # noqa: E402

SPLIT_DIR = os.path.join(ROOT, "data", "raw", "semeval2025_task7_data", "train_dev_sets")
CACHE = os.path.join(ROOT, "cache", "intfloat--multilingual-e5-large", "train_dev_sets", "both_posts")
OUT = os.path.join(ROOT, "results", "truncation_ablation.md")
BEGIN, END = "<!-- TABLES:BEGIN (generated by scripts/truncation_ablation.py) -->", "<!-- TABLES:END -->"
RUNS = [  # (suffix of run name, label)
    ("orig", "reference: orig"), ("eng", "reference: eng"), ("both", "reference: both"),
    ("origeng_max", "A: orig+eng max"), ("origeng_mean", "A: orig+eng mean"), ("origeng_rrf", "A: orig+eng RRF (k=60)"),
    ("origeng_both_mean", "A: orig+eng+both mean"),
    ("both_chunkmax", "B: both, chunks max"), ("both_chunkmean", "B: both, chunks mean-emb"),
]
TRACKS = (("mono", "monolingual"), ("cross", "crosslingual"))


def load_preds(run):
    with open(os.path.join(ROOT, "results", run, "predictions.json"), encoding="utf-8") as f:
        return {int(p): v for p, v in json.load(f).items()}


def main():
    ids, ntok = np.load(os.path.join(CACHE, "ids.npy")), np.load(os.path.join(CACHE, "ntok.npy"))
    over = {int(i) for i, n in zip(ids, ntok) if n > 512}
    md, summary = [], {}
    for short, track in TRACKS:
        units = eval_units(SPLIT_DIR, track, "dev")
        gold = {int(p): set(v) for p, v in load_reference(SPLIT_DIR, track).items()}
        langs = {p: u["lang"] for u in units for p in u["post_ids"]}
        post_ids = list(langs)
        aff = [p for p in post_ids if p in over]
        una = [p for p in post_ids if p not in over]
        md.append(f"### {track}: {len(post_ids)} dev posts, {len(aff)} affected ({len(aff) / len(post_ids):.1%}), {len(una)} unaffected\n")
        if track == "monolingual":
            md.append("Affected posts per language (n affected / n posts): " + ", ".join(
                f"{l} {sum(1 for p in aff if langs[p] == l)}/{sum(1 for p in post_ids if langs[p] == l)}" for l in sorted(set(langs.values()))) + "\n")
        md.append("| run | variant | S@10 overall | MRR overall | S@10 affected | MRR affected | S@10 unaffected | MRR unaffected |")
        md.append("|---|---|---|---|---|---|---|---|")
        rows = {}
        for suffix, label in RUNS:
            run = f"dense_{short}_dev_{suffix}"
            preds = load_preds(run)
            m = evaluate(preds, gold, langs, k=10)
            sa, su = subset_metrics(preds, gold, langs, aff), subset_metrics(preds, gold, langs, una)
            s = official_score(m, track)
            r = m["macro_mrr"] if track == "monolingual" else m["mrr"]
            rows[suffix] = (s, r, sa["s_at_k"], sa["mrr"], su["s_at_k"], su["mrr"], m)
            md.append(f"| {run} | {label} | {s:.4f} | {r:.4f} | {sa['s_at_k']:.4f} | {sa['mrr']:.4f} | {su['s_at_k']:.4f} | {su['mrr']:.4f} |")
        md.append("")
        ref_name = "both" if track == "monolingual" else "eng"
        cand = [k for k, _ in RUNS[3:]]
        best = max(cand, key=lambda k: rows[k][0])
        bs, rs = rows[best][0], rows[ref_name][0]
        md.append(f"Best variant ({track}): **dense_{short}_dev_{best}** S@10 {bs:.4f} vs reference dense_{short}_dev_{ref_name} {rs:.4f} "
                  f"(delta {bs - rs:+.4f}); MRR {rows[best][1]:.4f} vs {rows[ref_name][1]:.4f} ({rows[best][1] - rows[ref_name][1]:+.4f}). "
                  f"On affected posts: {rows[best][2]:.4f} vs {rows[ref_name][2]:.4f} ({rows[best][2] - rows[ref_name][2]:+.4f}).\n")
        if track == "monolingual":
            md.append(f"Per-language S@10, best variant ({best}) vs reference (both):\n")
            md.append("| language | n | reference both | best | delta |")
            md.append("|---|---|---|---|---|")
            pb, pr = rows[best][6]["per_language"], rows["both"][6]["per_language"]
            for l in sorted(pb):
                md.append(f"| {l} | {pb[l]['n']} | {pr[l]['s_at_k']:.4f} | {pb[l]['s_at_k']:.4f} | {pb[l]['s_at_k'] - pr[l]['s_at_k']:+.4f} |")
            md.append("")
        summary[track] = (len(aff), len(post_ids))
    block = BEGIN + "\n" + "\n".join(md) + "\n" + END
    text = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else "# S2-4 truncation ablation\n\n" + block + "\n"
    if BEGIN in text:
        text = text[: text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    else:
        text += "\n" + block + "\n"
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("\n".join(md))


if __name__ == "__main__":
    main()
